str = "Binod Dey"
print(str)
print(str[0]) #indexing
print(str[0:5]) #slicing
print(str[0:5:2]) #slicing with step
print(str[-1]) #last character
print(str[-5:-1]) #slicing from end

print(len(str))

print(str.lower())
print(str.upper())

print(str.replace("Binod", "Ankit"))
print(str.find("Dey")) #index of first occurrence of substring

print(str.count("D")) #count of substring
print(str.capitalize())

print("Binod" in str)



