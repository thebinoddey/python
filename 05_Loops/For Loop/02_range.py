seq = range(5) 
for i in seq: #range given in seq
    print(i)
    
for i in range(1,11): # range(start, stop)
    print(i)
    
for i in range(1,11,2): #range(start, stop, step)
    print(i)
    
for i in range(10,0,-1): #range(start, stop, step) this gives negative or backward numbers
    print(i)